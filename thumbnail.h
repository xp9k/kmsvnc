#pragma once

#include <rfb/rfb.h>

/*
 * Миниатюры dno-tool: клиент объявляет псевдокодировку и получает в ответ
 * подтверждение. Только после него клиент присылает желаемый размер, и сервер
 * отдаёт этому клиенту кадр, уменьшенный в целое число раз. Остальные клиенты
 * (просмотр, управление) продолжают получать полный кадр.
 *
 * С версии 2 клиент может ставить в байте флагов сообщения размера
 * KMSVNC_THUMBNAIL_FLAG_CAPTURE перед каждым запросом кадра: сервер снимает
 * экран и только после этого отвечает на запрос (снимок по запросу).
 *
 * С версии 3 есть вторая псевдокодировка KMSVNC_LIVE_ENCODING — «живой»
 * клиент: окно просмотра или управления, которому нужен уменьшенный кадр
 * (экран 4K). Подтверждение и сообщение размера те же (в подтверждении —
 * эта псевдокодировка). Такой клиент снимается с полной частотой, как обычный,
 * и на удержание не ставится (флаг снимка игнорируется). Отдельная
 * псевдокодировка, а не флаг: libvncserver не отключает расширение при
 * повторном SetEncodings, и сервер версии ≤ 2 считал бы окно, объявившее
 * KMSVNC_THUMBNAIL_ENCODING, миниатюрой (снимок раз в секунду). Новую
 * псевдокодировку прежний сервер просто не знает.
 */
#define KMSVNC_THUMBNAIL_ENCODING 0x444E4F54 /* "DNOT" */
#define KMSVNC_LIVE_ENCODING 0x444E4F4C /* "DNOL" */
#define KMSVNC_THUMBNAIL_MESSAGE 0xC4
#define KMSVNC_THUMBNAIL_VERSION 3
#define KMSVNC_THUMBNAIL_FLAG_CAPTURE 0x01

/* Регистрирует расширение (до rfbInitServer). */
void thumbnail_register(void);
/*
 * Нужно ли снимать экран на этом такте. live — у клиента полного кадра
 * (не пассивной миниатюры) открыт запрос обновления.
 */
int thumbnail_capture_due(rfbScreenInfoPtr server, int live);
/* Клиент миниатюр (не «живой»): снимается по правилам миниатюр. */
int thumbnail_client_passive(rfbClientPtr cl);
/* Снимок готов: отпустить клиентов, ждавших его; changed — экран изменился. */
void thumbnail_capture_finished(rfbScreenInfoPtr server, int changed);
